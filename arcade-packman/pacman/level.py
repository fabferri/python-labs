LEVELS = [LEVEL_1, LEVEL_2, LEVEL_3]


@dataclass
class LevelData:
    walls: set[tuple[int, int]]
    pellets: set[tuple[int, int]]
    player_spawns: list[tuple[int, int]]
    ghost_spawns: list[tuple[int, int]]
    tunnel_rows: set[int]
    width: int
    height: int


# Load and parse level data for the given index.
def load_level(level_index: int = 0) -> LevelData:
    layout = LEVELS[level_index % len(LEVELS)]
    walls: set[tuple[int, int]] = set()
    pellets: set[tuple[int, int]] = set()
    player_spawns: list[tuple[int, int]] = []
    ghost_spawns: list[tuple[int, int]] = []
    tunnel_rows: set[int] = set()

    for y, row in enumerate(layout):
        if row and (row[0] == " " or row[-1] == " "):
            tunnel_rows.add(y)
        for x, char in enumerate(row):
            if char == "#":
                walls.add((x, y))
            elif char == ".":
                pellets.add((x, y))
            elif char == "P":
                player_spawns.append((x, y))
            elif char == "G":
                ghost_spawns.append((x, y))

    return LevelData(
        walls=walls,
        pellets=pellets,
        player_spawns=player_spawns,
        ghost_spawns=ghost_spawns,
        tunnel_rows=tunnel_rows,
        width=max(len(row) for row in layout),
        height=len(layout),
    )


# Return the number of available levels.
def get_level_count() -> int:
    return len(LEVELS)

